CREATE TABLE room_reservations
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id    BIGINT      NOT NULL,
    booking_id BIGINT      NOT NULL,
    request_id UUID        NOT NULL,
    start_date DATE,
    end_date   DATE,
    state      VARCHAR(16) NOT NULL,
    CONSTRAINT fk_room_reservations_room FOREIGN KEY (room_id) REFERENCES rooms (id),
    CONSTRAINT uk_room_reservations_booking_room UNIQUE (booking_id, room_id),
    CONSTRAINT ck_room_reservations_dates CHECK (
        (start_date IS NOT NULL AND end_date IS NOT NULL AND start_date < end_date)
            OR (state = 'RELEASED' AND start_date IS NULL AND end_date IS NULL)
        )
);
